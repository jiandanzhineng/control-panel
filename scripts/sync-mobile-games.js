#!/usr/bin/env node
'use strict';

// PC game sources are canonical. Mobile receives the same UI/assets and a
// synchronous GameCore adapter around the same hosted cores, without gameplay edits.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const GAME_SOURCES = {
  'pressure-edging-v2': 'backend/games/pressure-edging-v2',
  'pushup-detection': 'backend/games/pushup-detection',
  'drink-pee-unlock': 'backend/games/drink-pee-unlock',
  'pelvic-training': 'backend/games/pelvic-training',
  'pressure-edging': 'backend/games/pressure-edging',
  'maid-punishment': 'backend/games/maid-punishment',
  'rc-car': 'backend/games/rc-car',
  'surge-edging': 'play-registry/games/surge-edging',
};
const GAME_IDS = Object.keys(GAME_SOURCES);
const HOST_CORES = {
  'pressure-edging-v2': ['backend/game-runtime/cores/pressure-edging-v2-core.js', 'PressureEdgingV2Core', './pressure-edging-v2-manifest'],
  'surge-edging': ['backend/game-runtime/cores/surge-edging-core.js', 'SurgeEdgingCore', './surge-edging-manifest'],
  'maid-punishment': ['backend/games/maid-punishment/game-core.js', 'MaidPunishmentCore'],
  'rc-car': ['backend/games/rc-car/game-core.js', 'RcCarCore'],
};

// Both repositories store text with LF. Keep checksums stable after a Git
// checkout even when a Windows editor writes CRLF in the canonical tree.
function readSource(file) {
  const data = fs.readFileSync(file);
  return /\.(js|json|html|css|md|txt|svg)$/i.test(file)
    ? Buffer.from(data.toString('utf8').replace(/\r\n/g, '\n')) : data;
}

function mobileAdapter(ctorName) {
  let core = null;
  let started = false;
  function randomFor(seed) {
    let state = (Number(seed) >>> 0) || 0x6d2b79f5;
    return function () {
      state = (state + 0x6d2b79f5) | 0;
      let value = Math.imul(state ^ (state >>> 15), 1 | state);
      value = (value + Math.imul(value ^ (value >>> 7), 61 | value)) ^ value;
      return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
    };
  }
  globalThis.GameCore = {
    create(input) {
      core = new globalThis.__MobileSharedCore[ctorName]({ params: input.params || {}, random: randomFor(input.randomSeed) });
      started = false;
    },
    dispatch(input) {
      if (!core) throw new Error('GameCore 未创建');
      const nowMs = Number.isFinite(input.nowMs) ? input.nowMs : Date.now();
      const effects = [], logs = [];
      let result;
      function collect(next) {
        if (next.ok === false) throw Object.assign(new Error(next.message), { code: next.code });
        result = next;
        effects.push(...next.effects); logs.push(...next.logs);
      }
      if (!started) { collect(core.start(nowMs)); started = true; }
      else result = core.result ? core.result(nowMs) : core._ok(nowMs);
      for (const event of input.events || []) {
        if (event.type === 'tick') collect(core.step({ nowMs, events: [] }));
        else if (event.type === 'sensor') collect(core.step({ nowMs, events: [event] }));
        else if (event.type === 'pause') collect(core.pause(nowMs));
        else if (event.type === 'resume') collect(core.resume(nowMs));
        else if (event.type === 'stop') collect(core.stop(nowMs, event.reason || 'stop'));
        else if (event.type === 'params') collect(core.setParams(event.params || {}));
        else if (event.type === 'action' && event.action) collect(core.action(event.action, event.payload || {}, nowMs));
        else collect(core.step({ nowMs, events: [event] }));
      }
      return { ...result, effects, logs };
    },
    exportCheckpoint() {
      if (!core) throw new Error('GameCore 未创建');
      return { snapshot: core.snapshot(), params: { ...core.cfg } };
    },
    dispose() { core = null; started = false; },
  };
}

function buildMobileCore(gameId) {
  const [file, ctorName, dependency] = HOST_CORES[gameId];
  const source = readSource(path.join(ROOT, file)).toString('utf8');
  const manifest = dependency ? require(path.resolve(ROOT, path.dirname(file), dependency)) : null;
  return `// Generated by control-panel/scripts/sync-mobile-games.js. Do not edit.\n(function () {\nconst module = { exports: {} };\nfunction require(id) { if (id === ${JSON.stringify(dependency || '')}) return ${JSON.stringify(manifest)}; throw new Error('Unknown module: ' + id); }\n${source}\nglobalThis.__MobileSharedCore = module.exports;\n${gameId === 'pressure-edging-v2' ? 'globalThis.__MobilePressureCore = module.exports;\n' : ''}(${mobileAdapter.toString()})(${JSON.stringify(ctorName)});\n})();\nif (typeof module === 'object' && module.exports) module.exports = globalThis.__MobileSharedCore;\n`;
}
function buildMobilePressureCore() { return buildMobileCore('pressure-edging-v2'); }

function sourceFiles() {
  const files = new Map();
  function collect(dir, prefix) {
    for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
      if (item.isDirectory()) collect(path.join(dir, item.name), `${prefix}/${item.name}`);
      else files.set(`${prefix}/${item.name}`, readSource(path.join(dir, item.name)));
    }
  }
  for (const id of GAME_IDS) collect(path.join(ROOT, GAME_SOURCES[id]), id);
  files.set('_shared/game-i18n.js', readSource(path.join(ROOT, 'backend/public/game-i18n.js')));
  const pressureHtml = files.get('pressure-edging-v2/index.html').toString();
  const manifest = JSON.parse(pressureHtml.match(/<script[^>]*id="game-manifest"[^>]*>([\s\S]*?)<\/script>/)[1]);
  files.set('_shared/pressure-edging-v2-manifest.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'));
  files.set('pressure-edging-v2/game-core.js', Buffer.from(buildMobilePressureCore()));
  const hostManifests = [], renderers = {};
  for (const id of Object.keys(HOST_CORES)) {
    const html = files.get(`${id}/index.html`).toString();
    hostManifests.push(JSON.parse(html.match(/<script[^>]*id="game-manifest"[^>]*>([\s\S]*?)<\/script>/)[1]));
    files.set(`${id}/game-core.js`, Buffer.from(buildMobileCore(id)));
    const [corePath, , dependency] = HOST_CORES[id];
    if (dependency) {
      files.set(`cores/${path.basename(corePath)}`, readSource(path.join(ROOT, corePath)));
      files.set(`cores/${path.basename(dependency)}.js`, readSource(path.resolve(ROOT, path.dirname(corePath), `${dependency}.js`)));
    }
    renderers[id] = {
      scripts: ['_shared/game-runtime-mobile-bridge.js', '_shared/game-i18n.js', ...(files.has(`${id}/i18n.js`) ? [`${id}/i18n.js`] : []), `${id}/game.js`],
      voices: [...files.keys()].filter(name => name.startsWith(`${id}/voices/`) && name.endsWith('.mp3')).map(name => name.slice(id.length + 1)),
    };
  }
  files.set('_shared/game-host-manifests.json', Buffer.from(JSON.stringify(hostManifests, null, 2) + '\n'));
  files.set('_shared/game-host-renderers.json', Buffer.from(JSON.stringify(renderers, null, 2) + '\n'));
  const checksums = Object.fromEntries([...files].map(([name, data]) => [name, crypto.createHash('sha256').update(data).digest('hex')]));
  files.set('_shared/shared-game-sources.json', Buffer.from(JSON.stringify({ source: 'control-panel', games: GAME_IDS, files: checksums }, null, 2) + '\n'));
  return files;
}

function sync(mobileRoot, check = false) {
  const differences = [];
  for (const [relative, data] of sourceFiles()) {
    const target = path.join(mobileRoot, 'assets/games', relative);
    if (fs.existsSync(target) && fs.readFileSync(target).equals(data)) continue;
    differences.push(relative);
    if (!check) { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, data); }
  }
  if (check && differences.length) throw new Error(`Shared game assets differ:\n${differences.join('\n')}`);
  return differences;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const mobileRoot = args.find(arg => !arg.startsWith('--'));
  if (!mobileRoot) throw new Error('Usage: node scripts/sync-mobile-games.js <mobile-repo> [--check]');
  const changed = sync(path.resolve(mobileRoot), args.includes('--check'));
  console.log(`Shared games ${args.includes('--check') ? 'verified' : 'synchronized'} (${changed.length} changed files).`);
}
module.exports = { buildMobileCore, buildMobilePressureCore, sourceFiles, sync };
